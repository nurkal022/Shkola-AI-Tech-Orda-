"""
Лекция 16: Базовый Crew
========================
Минимальная структура: один Agent, одна Task, один Crew.
Показывает базовые концепции CrewAI.
"""

import os
from crewai import Agent, Task, Crew, Process
from dotenv import load_dotenv

# Загружаем .env из корневой папки проекта
load_dotenv(dotenv_path="/Users/nurlykhan/TechOrda/.env")

if not os.getenv("OPENAI_API_KEY"):
    print("❌ OPENAI_API_KEY не найден в .env файле")
    exit(1)

# ============================================================
# 1. Создание агента
# ============================================================

agent = Agent(
    role="Assistant",
    goal="Помогать пользователю с задачами",
    backstory="Ты полезный помощник, который всегда готов помочь.",
    verbose=True,
)

# ============================================================
# 2. Создание задачи
# ============================================================

task = Task(
    description="Объясни что такое мультиагентные системы простыми словами",
    expected_output="Краткое объяснение мультиагентных систем (2-3 предложения)",
    agent=agent,
)

# ============================================================
# 3. Создание Crew
# ============================================================

crew = Crew(
    agents=[agent],
    tasks=[task],
    process=Process.sequential,
    verbose=True,
)

# ============================================================
# 4. Запуск
# ============================================================

if __name__ == "__main__":
    print("="*60)
    print("🚣 Базовый Crew")
    print("="*60)
    print()
    
    result = crew.kickoff()
    
    print()
    print("="*60)
    print("✅ РЕЗУЛЬТАТ:")
    print("="*60)
    print(result)
