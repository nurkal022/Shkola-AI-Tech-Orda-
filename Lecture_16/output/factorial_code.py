def factorial(n: int) -> int:
    """
    Вычисляет факториал неотрицательного целого числа n.

    Факториал n (обозначается n!) — произведение всех положительных целых чисел от 1 до n.
    По определению: 0! = 1.

    Аргументы:
        n (int): неотрицательное целое число

    Возвращает:
        int: факториал числа n

    Исключения:
        TypeError: если n не является целым числом
        ValueError: если n отрицательное число
    """
    if not isinstance(n, int):
        raise TypeError("Аргумент n должен быть целым числом.")
    if n < 0:
        raise ValueError("Аргумент n не может быть отрицательным.")

    result = 1
    for i in range(2, n + 1):
        result *= i
    return result
