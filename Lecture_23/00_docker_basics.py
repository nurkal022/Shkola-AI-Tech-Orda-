# ============================================================
# 1. ЧТО ТАКОЕ DOCKER?
# ============================================================
#
# Docker — это платформа для контейнеризации приложений.
#
# Проблема БЕЗ Docker:
#   - "У меня работает, на сервере — нет"
#   - Python 3.11 vs 3.12, разные версии библиотек
#   - Один разработчик на Mac, другой на Linux
#   - Деплой: "установи вот эти 20 пакетов..."
#
# Docker РЕШАЕТ:
#   - Приложение + все зависимости = один контейнер
#   - Работает одинаково везде: Mac, Linux, Windows, облако
#   - Деплой: "docker run image" — и всё
#
# ┌─────────────────────────────────────────┐
# │           Docker контейнер              │
# │  ┌─────────────────────────────────┐    │
# │  │  Ваше FastAPI приложение        │    │
# │  │  Python 3.12                    │    │
# │  │  fastapi, uvicorn, openai       │    │
# │  │  Все зависимости                │    │
# │  └─────────────────────────────────┘    │
# │  Изолированная файловая система         │
# │  Своя сеть, свои процессы              │
# └─────────────────────────────────────────┘
#
# Контейнер = лёгкая виртуальная машина (но быстрее!)

# ============================================================
# 2. КЛЮЧЕВЫЕ ПОНЯТИЯ
# ============================================================
#
# Image (образ):
#   - Шаблон для контейнера (как класс в ООП)
#   - Создаётся из Dockerfile
#   - Хранится в registry (Docker Hub, GitHub Container Registry)
#
# Container (контейнер):
#   - Запущенный экземпляр образа (как объект в ООП)
#   - Изолированный процесс с своей файловой системой
#   - Можно запустить много контейнеров из одного образа
#
# Dockerfile:
#   - Инструкция по сборке образа
#   - Каждая строка = новый слой (layer)
#   - Слои кешируются — пересборка быстрая!
#
# Docker Compose:
#   - Запуск нескольких контейнеров вместе
#   - Один файл docker-compose.yml
#   - Удобно для: API + БД + Redis + Nginx

# ============================================================
# 3. DOCKERFILE — ПОШАГОВЫЙ РАЗБОР
# ============================================================
#
# Наш Dockerfile:
#
#   FROM python:3.12-slim          # Базовый образ (Python уже установлен)
#
#   ENV PYTHONDONTWRITEBYTECODE=1   # Не создавать .pyc
#   ENV PYTHONUNBUFFERED=1          # Логи без задержки
#   ENV PORT=8000                   # Порт (можно переопределить)
#
#   WORKDIR /app                    # Рабочая директория внутри контейнера
#
#   COPY app/requirements.txt .     # Копируем ТОЛЬКО requirements.txt
#   RUN pip install -r requirements.txt  # Устанавливаем зависимости (кешируется!)
#
#   COPY app/main.py .              # Копируем код приложения
#
#   EXPOSE ${PORT}                  # Документируем порт
#
#   HEALTHCHECK ...                 # Проверка здоровья
#
#   CMD uvicorn main:app --host 0.0.0.0 --port ${PORT}   # Запуск
#
# ─────────────────────────────────────────────
# ВАЖНО: Порядок COPY имеет значение!
# ─────────────────────────────────────────────
#
# ПРАВИЛЬНО (быстрая пересборка):
#   COPY requirements.txt .    <-- кешируется если не изменился
#   RUN pip install ...        <-- кешируется если requirements не изменился
#   COPY main.py .             <-- пересобирается только этот слой
#
# НЕПРАВИЛЬНО (медленная пересборка):
#   COPY . .                   <-- любое изменение кода = переустановка pip

# ============================================================
# 4. ОСНОВНЫЕ КОМАНДЫ DOCKER
# ============================================================

DOCKER_COMMANDS = """
# ─────────────────────────────────────
# Сборка образа
# ─────────────────────────────────────

docker build -t ai-chat-api .
#   -t ai-chat-api    имя образа (tag)
#   .                  контекст сборки (текущая папка)

docker build -t ai-chat-api:v2 .
#   :v2               версия (по умолчанию :latest)

# ─────────────────────────────────────
# Запуск контейнера
# ─────────────────────────────────────

docker run ai-chat-api
#   Запуск в foreground (Ctrl+C для остановки)

docker run -d ai-chat-api
#   -d                 detached (в фоне)

docker run -p 8000:8000 ai-chat-api
#   -p 8000:8000       проброс порта: host:container

docker run -e OPENAI_API_KEY=sk-xxx ai-chat-api
#   -e KEY=VALUE       переменная окружения

docker run --name my-api -d -p 8000:8000 -e OPENAI_API_KEY=sk-xxx ai-chat-api
#   --name my-api      имя контейнера

# ─────────────────────────────────────
# Управление контейнерами
# ─────────────────────────────────────

docker ps                     # Запущенные контейнеры
docker ps -a                  # Все контейнеры (включая остановленные)
docker stop my-api            # Остановить контейнер
docker start my-api           # Запустить остановленный
docker restart my-api         # Перезапустить
docker rm my-api              # Удалить контейнер
docker logs my-api            # Логи контейнера
docker logs -f my-api         # Логи в реальном времени (follow)
docker exec -it my-api bash   # Зайти внутрь контейнера

# ─────────────────────────────────────
# Управление образами
# ─────────────────────────────────────

docker images                 # Список образов
docker rmi ai-chat-api        # Удалить образ
docker system prune           # Очистить неиспользуемые данные

# ─────────────────────────────────────
# Docker Compose
# ─────────────────────────────────────

docker compose up              # Запустить все сервисы
docker compose up -d           # В фоне
docker compose up --build      # Пересобрать и запустить
docker compose down            # Остановить и удалить контейнеры
docker compose logs -f         # Логи всех сервисов
docker compose ps              # Статус сервисов
docker compose exec api bash   # Зайти внутрь сервиса 'api'

# ─────────────────────────────────────
# Docker Hub (registry)
# ─────────────────────────────────────

docker login                               # Авторизация
docker tag ai-chat-api username/ai-chat-api:v1   # Тег для push
docker push username/ai-chat-api:v1               # Загрузить образ
docker pull username/ai-chat-api:v1               # Скачать образ
"""

# ============================================================
# 5. DOCKER COMPOSE — РАЗБОР
# ============================================================
#
# docker-compose.yml:
#
#   services:
#     api:                              # Имя сервиса
#       build:                          # Сборка из Dockerfile
#         context: .
#         dockerfile: Dockerfile
#       ports:
#         - "8000:8000"                 # Проброс порта
#       environment:                    # Переменные окружения
#         - OPENAI_API_KEY=${OPENAI_API_KEY}
#         - PORT=8000
#       healthcheck:                    # Проверка здоровья
#         test: [...]
#         interval: 30s
#       restart: unless-stopped         # Перезапуск при падении
#
# Переменная ${OPENAI_API_KEY} берётся из:
#   1. Shell: export OPENAI_API_KEY=sk-xxx && docker compose up
#   2. Файл .env в той же папке (Docker Compose читает его автоматически)

# ============================================================
# 6. BEST PRACTICES
# ============================================================
#
# 1. Используйте python:3.12-slim (не full — экономия ~600MB)
# 2. Копируйте requirements.txt отдельно от кода (кеш слоёв)
# 3. Не храните секреты в Dockerfile! Используйте -e или .env
# 4. Добавьте .dockerignore (не копировать .git, __pycache__)
# 5. Один процесс = один контейнер
# 6. Используйте HEALTHCHECK
# 7. Логируйте в stdout (Docker собирает логи сам)
# 8. Не запускайте от root (в продакшене: USER nonroot)

