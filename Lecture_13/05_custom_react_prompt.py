"""
Лекция 13: Кастомизация ReAct промпта
======================================
Демонстрация создания собственного ReAct промпта для специфических задач.
"""

from langchain_openai import ChatOpenAI
from langchain.agents import create_react_agent, AgentExecutor
from langchain_core.prompts import PromptTemplate
from langchain_core.tools import tool
from dotenv import load_dotenv
import os

load_dotenv()

if not os.getenv("OPENAI_API_KEY"):
    print("❌ OPENAI_API_KEY не найден в .env файле")
    exit(1)

# ============================================================
# Создание инструментов
# ============================================================

@tool
def calculate(expression: str) -> str:
    """Вычисляет математическое выражение."""
    try:
        result = eval(expression, {"__builtins__": {}}, {})
        return f"Результат: {result}"
    except Exception as e:
        return f"Ошибка: {str(e)}"


@tool
def get_current_date() -> str:
    """Возвращает текущую дату в формате ДД.ММ.ГГГГ."""
    from datetime import datetime
    return f"Текущая дата: {datetime.now().strftime('%d.%m.%Y')}"


tools = [calculate, get_current_date]
llm = ChatOpenAI(model="gpt-4o-mini", temperature=0)

# ============================================================
# Кастомный ReAct промпт (на русском языке)
# ============================================================

print("="*60)
print("📝 СОЗДАНИЕ КАСТОМНОГО ReAct ПРОМПТА")
print("="*60)
print()

custom_react_template = """Ты эксперт-помощник, который отвечает на вопросы используя доступные инструменты.

Доступные инструменты:
{tools}

Используй следующий формат для ответа:

Вопрос: исходный вопрос пользователя
Размышление: твои мысли о том, что нужно сделать
Действие: название инструмента (один из [{tool_names}])
Ввод: параметры для инструмента
Результат: результат выполнения инструмента
... (этот цикл Размышление/Действие/Ввод/Результат может повторяться N раз)
Размышление: теперь я знаю финальный ответ
Итоговый ответ: финальный ответ на исходный вопрос

ВАЖНО:
- Всегда думай вслух (показывай Размышление)
- Используй инструменты когда это необходимо
- Отвечай на русском языке
- Будь подробным в объяснениях

Начни!

Вопрос: {input}
Размышление:{agent_scratchpad}
"""

custom_react_prompt = PromptTemplate.from_template(custom_react_template)

print("📄 КАСТОМНЫЙ ПРОМПТ:")
print("─" * 60)
print(custom_react_template)
print()

# ============================================================
# Сравнение со стандартным промптом
# ============================================================

print("="*60)
print("🔍 СРАВНЕНИЕ С СТАНДАРТНЫМ ПРОМПТОМ")
print("="*60)
print()

print("📌 ОТЛИЧИЯ КАСТОМНОГО ПРОМПТА:")
print("─" * 60)
differences = """
1. ЯЗЫК:
   ✅ Кастомный: полностью на русском
   ⚠️ Стандартный: на английском

2. ТЕРМИНОЛОГИЯ:
   ✅ Кастомный: "Размышление", "Действие", "Итоговый ответ"
   ⚠️ Стандартный: "Thought", "Action", "Final Answer"

3. ИНСТРУКЦИИ:
   ✅ Кастомный: "Всегда думай вслух", "Будь подробным"
   ⚠️ Стандартный: базовая инструкция

4. КОНТЕКСТ:
   ✅ Кастомный: "Ты эксперт-помощник"
   ⚠️ Стандартный: общая инструкция
"""

print(differences)
print()

# ============================================================
# Создание агента с кастомным промптом
# ============================================================

print("="*60)
print("🤖 СОЗДАНИЕ АГЕНТА С КАСТОМНЫМ ПРОМПТОМ")
print("="*60)
print()

agent = create_react_agent(llm, tools, custom_react_prompt)

agent_executor = AgentExecutor(
    agent=agent,
    tools=tools,
    verbose=True,
    handle_parsing_errors=True,
    max_iterations=5,
)

print("   ✅ Агент создан с кастомным промптом")
print()

# ============================================================
# Демонстрация работы
# ============================================================

print("="*60)
print("💬 ДЕМОНСТРАЦИЯ РАБОТЫ")
print("="*60)
print()

test_queries = [
    "Сколько будет 25 * 17?",
    "Какая сегодня дата? Умножь день месяца на 10.",
]

for i, query in enumerate(test_queries, 1):
    print(f"📌 ПРИМЕР {i}: {query}")
    print("─" * 60)
    print()
    
    result = agent_executor.invoke({"input": query})
    
    print(f"\n✅ Итоговый ответ: {result['output']}\n")
    print("="*60)
    print()

# ============================================================
# Примеры других кастомизаций
