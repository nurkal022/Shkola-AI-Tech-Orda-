# ============================================================
# Интерактивный режим
# ============================================================

print("="*60)
print("💬 ИНТЕРАКТИВНЫЙ РЕЖИМ")
print("="*60)
print("""
   Попробуйте агента с кастомным промптом.
   Обратите внимание на:
   • Русский язык в рассуждениях
   • Подробные объяснения
   • Формат "Размышление/Действие/Результат"
   
   Введите 'exit' для выхода.
""")
print("="*60)

while True:
    try:
        user_input = input("\n🤔 Ваш запрос: ").strip()
        
        if user_input.lower() in ['exit', 'quit', 'выход', 'q']:
            print("\n👋 До свидания!")
            break
        
        if not user_input:
            print("⚠️ Пустой запрос, попробуйте ещё раз")
            continue
        
        print(f"\n{'─'*60}")
        print(f"🔍 Обработка: «{user_input}»")
        print(f"{'─'*60}\n")
        
        result = agent_executor.invoke({"input": user_input})
        
        print(f"\n{'─'*60}")
        print(f"✅ ИТОГОВЫЙ ОТВЕТ:")
        print(f"{'─'*60}")
        print(f"{result['output']}\n")
        
    except KeyboardInterrupt:
        print("\n\n👋 До свидания!")
        break
    except Exception as e:
        print(f"\n❌ Ошибка: {e}")
        print("Попробуйте ещё раз или введите 'exit' для выхода")
